#!/usr/bin/env python3
"""Clone a video job while stripping derived artifacts.

A cloned job must not inherit paths from the source job. This module copies
only the request/script configuration and removes every derived section that
will be regenerated by later pipeline stages (assets, timeline, subtitles,
render, validation, review, etc.).
"""

import argparse
import json
import shutil
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


DERIVED_KEYS = {
    "assets",
    "timeline",
    "renderTimeline",
    "subtitles",
    "render",
    "assetValidation",
    "validation",
    "review",
    "resolvedConfig",
    "updatedAt",
}


def _remove_derived_artifacts(data: dict[str, Any]) -> dict[str, Any]:
    """Return a deep copy of metadata with derived artifact sections removed."""
    cleaned: dict[str, Any] = json.loads(json.dumps(data))
    for key in DERIVED_KEYS:
        cleaned.pop(key, None)
    return cleaned


def _apply_scene_patches(script: dict[str, Any], patches: dict[int, dict[str, Any]]) -> None:
    """Apply per-scene visualPlan patches by scene number."""
    if not patches:
        return
    for scene in script.get("scenes", []):
        sn = scene.get("sceneNumber")
        if sn in patches:
            scene.setdefault("visualPlan", {}).update(patches[sn])


def clone_job(
    source_metadata_path: Path,
    target_video_dir: Path | None = None,
    job_id: str | None = None,
    scene_patches: dict[int, dict[str, Any]] | None = None,
    status: str = "SCRIPT_READY",
) -> Path:
    """Clone a job, strip inherited artifacts, and write a fresh metadata.json.

    Args:
        source_metadata_path: path to the source job metadata.json.
        target_video_dir: directory where the new metadata.json will be written.
            If None, a sibling directory with the new jobId is created.
        job_id: new jobId. If None, generated from timestamp.
        scene_patches: mapping sceneNumber -> visualPlan fields to override.
        status: initial status for the cloned job.

    Returns:
        Path to the new metadata.json.
    """
    source_metadata_path = source_metadata_path.resolve()
    source_data = json.loads(source_metadata_path.read_text())
    project_root = source_metadata_path.parents[3]

    if job_id is None:
        job_id = f"bw-v8-{datetime.now(timezone.utc).strftime('%Y%m%d-%H%M%S')}"

    if target_video_dir is None:
        data_videos = project_root / "data" / "videos"
        target_video_dir = data_videos / f"validation-realistic-berlin-wall-v8-assets-{datetime.now(timezone.utc).strftime('%Y%m%d-%H%M%S')}"

    target_video_dir.mkdir(parents=True, exist_ok=True)

    cleaned = _remove_derived_artifacts(source_data)
    cleaned["jobId"] = job_id
    cleaned["status"] = status
    cleaned["createdAt"] = datetime.now(timezone.utc).isoformat()
    cleaned["updatedAt"] = cleaned["createdAt"]

    script = cleaned.get("script")
    if script and scene_patches:
        _apply_scene_patches(script, scene_patches)

    target_metadata = target_video_dir / "metadata.json"
    target_metadata.write_text(json.dumps(cleaned, indent=2, ensure_ascii=False) + "\n")
    return target_metadata


def main() -> int:
    parser = argparse.ArgumentParser(description="Clone a video job stripping derived artifacts.")
    parser.add_argument("source_metadata", help="Path to source metadata.json")
    parser.add_argument("--target-dir", help="Target video directory (default: auto-generated)")
    parser.add_argument("--job-id", help="New jobId (default: auto-generated)")
    parser.add_argument(
        "--scene-patch",
        action="append",
        metavar="SCENE:KEY=VALUE",
        help="Override a visualPlan field for a scene, e.g. '2:editorialRole=border_closure_construction'",
    )
    args = parser.parse_args()

    source_path = Path(args.source_metadata)
    target_dir = Path(args.target_dir) if args.target_dir else None

    scene_patches: dict[int, dict[str, Any]] = {}
    if args.scene_patch:
        for patch in args.scene_patch:
            scene_part, kv = patch.split(":", 1)
            key, value = kv.split("=", 1)
            sn = int(scene_part)
            scene_patches.setdefault(sn, {})[key] = value

    new_metadata = clone_job(source_path, target_dir, args.job_id, scene_patches)
    print(json.dumps({"jobId": json.loads(new_metadata.read_text())["jobId"],
                      "metadata": str(new_metadata)}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
